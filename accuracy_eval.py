@dataclass(frozen=True)
class Span:
    """A category plus a half-open character range, for gold labels and findings alike."""

    category: str
    start: int
    end: int

    def overlaps(self, other: "Span") -> bool:
        return self.category == other.category and self.start < other.end and other.start < self.end


def covers(spans: list[tuple[int, int]], start: int, end: int) -> bool:
    """True when the union of `spans` covers every character of [start, end).

    Union, not "some single span contains it": a name split across two findings
    is still fully redactable, and calling that a partial would understate the
    product. A gap anywhere inside the range is a partial, however small -- the
    uncovered characters are what ships.
    """
    cursor = start
    for span_start, span_end in sorted(spans):
        if span_end <= cursor:
            continue
        if span_start > cursor:
            return False
        cursor = max(cursor, span_end)
        if cursor >= end:
            return True
    return cursor >= end


@dataclass
class CategoryScore:
    gold: int = 0
    detected: int = 0
    fully_covered: int = 0
    findings: int = 0
    false_positives: int = 0

    @property
    def recall(self) -> float | None:
        return round(self.detected / self.gold, 4) if self.gold else None

    @property
    def full_span_recall(self) -> float | None:
        return round(self.fully_covered / self.gold, 4) if self.gold else None

    @property
    def precision(self) -> float | None:
        if not self.findings:
            return None
        return round((self.findings - self.false_positives) / self.findings, 4)

    def as_dict(self) -> dict:
        return {
            "gold": self.gold,
            "detected": self.detected,
            "fully_covered": self.fully_covered,
            "findings": self.findings,
            "false_positives": self.false_positives,
            "recall": self.recall,
            "full_span_recall": self.full_span_recall,
            "precision": self.precision,
        }


def score_spans(gold: list[Span], findings: list[Span]) -> dict[str, CategoryScore]:
    """Score findings against gold spans by OFFSET OVERLAP within a category.

    A gold span is *detected* when at least one same-category finding overlaps
    it, and *fully covered* when the union of those findings spans it end to end.
    A finding is a true positive when it overlaps at least one same-category gold
    span; findings in UNSCORED_CATEGORIES are left out of the precision figures
    entirely rather than counted as false positives.

    Findings are matched by identity of their (category, start, end) tuple, so a
    finding that covers two adjacent gold spans is one true positive rather than
    two -- double-counting it would let one over-wide match inflate precision.
    """
    scores: dict[str, CategoryScore] = collections.defaultdict(CategoryScore)
    matched_findings: set[tuple[str, int, int]] = set()

    for label in gold:
        score = scores[label.category]
        score.gold += 1
        hits = [finding for finding in findings if finding.overlaps(label)]
        if not hits:
            continue
        score.detected += 1
        for hit in hits:
            matched_findings.add((hit.category, hit.start, hit.end))
        if covers([(hit.start, hit.end) for hit in hits], label.start, label.end):
            score.fully_covered += 1

    for finding in findings:
        if finding.category in UNSCORED_CATEGORIES:
            continue
        score = scores[finding.category]
        score.findings += 1
        if (finding.category, finding.start, finding.end) not in matched_findings:
            score.false_positives += 1

    return dict(scores)


