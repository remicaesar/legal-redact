"""Measure detection accuracy on the HELD-OUT corpus. Not the regression ratchet.

This repo now has two accuracy tools and they answer different questions. Running
one in place of the other is the mistake this file exists to stop.

``accuracy_audit.py`` + ``gold/``  -- the REGRESSION RATCHET.
    Its corpus is fitted: the labels and the rules in ``legal_analyzer/privacy.py``
    have been edited in the same commits, its recall is 1.000 in every category,
    and CI asserts ``false_negative_count == 0``. That is a real guarantee -- the
    detector never silently loses a capability it had -- and it is worth keeping
    exactly as it is. It cannot produce a false negative, so it says nothing about
    capabilities the detector never had.

``accuracy_eval.py`` + ``eval/``   -- the MEASUREMENT (this file).
    Its corpus is generated by ``eval/generate_corpus.py``, which records each
    entity's offsets as it places them. Nothing here may be used to tune a rule
    (the one recorded exception, English person names, is stated in the caveat
    ``render_docs`` writes into docs/accuracy.md): the moment a detection rule is
    adjusted until this number goes up, this stops being a measurement and
    becomes a second ratchet.
    Its numbers are therefore REPORTED, not asserted at a floor.

Three differences from the audit's scoring, each of which was hiding something:

1. **Offsets, not substrings.** ``accuracy_audit.label_matches_finding`` credits a
   label when the finding's sample contains it *or* it contains the finding's
   sample, anywhere in the document. A finding of the right category with the
   right text at the wrong place scores as a hit, and so does a finding covering
   only part of the entity. Here a label is detected only when a same-category
   finding actually overlaps its span.
2. **Full-span coverage reported beside recall.** Redaction removes what a finding
   *covers*. ``ANKARA 7. ASLİYE HUKUK MAHKEMESİ`` matched by a finding that starts
   at ``7.`` leaves the city in the exported file, and plain recall calls that a
   hit. ``full_span_recall`` is the number that predicts the deliverable.
3. **Per category and per language.** A single blended recall is what let an
   English gap sit behind a Turkish average.

And one difference that is not about scoring at all: this runs the same documents
through ``.txt``, ``.docx`` and ``.pdf``. Every accuracy figure this repo had
before was measured on ``.txt``, so no number covered extraction -- and page
furniture in a PDF can put a footer digit between two words of a name, which
costs the surname without costing a single finding. A label that cannot be found
in the extracted text at all is counted as ``unlocatable`` and kept out of the
recall figures: that is an extraction failure, not a detection failure, and
adding them together would hide both.

Usage::

    python3 accuracy_eval.py                          # measure, print, write eval_report.json
    python3 accuracy_eval.py --formats txt            # skip the rendered formats
    python3 accuracy_eval.py --write-docs             # refresh docs/accuracy.md
    python3 accuracy_eval.py --check-docs             # fail if docs/accuracy.md is stale
"""

