def extract_pdf_with(engine: str, path: Path, max_chars: int = 400_000) -> str:
    """Run ONE of the two branches `extraction.extract_pdf_text` chooses between.

    This is not a third PDF text path: each branch below is the same call the
    product makes, with the same `normalize_layout` and the same cap. What it
    does not do is let `shutil.which` decide, because the point is to report both
    and the product's own dispatch can only ever report the one this machine has.

    If the two ever stop agreeing with `extract_text` on a machine that has
    poppler, `tests/test_accuracy_eval.py` says so.
    """
    from legal_analyzer.extraction import normalize_layout

    if engine == "poppler":
        if not shutil.which("pdftotext"):
            raise RuntimeError(
                "pdftotext (poppler) is not installed, so the pdf-poppler arm cannot run. "
                "Install poppler (brew install poppler / apt-get install poppler-utils), or "
                "pass --formats txt,docx,pdf-pypdf."
            )
        result = subprocess.run(
            ["pdftotext", "-layout", str(path), "-"],
            check=False,
            capture_output=True,
            text=True,
            timeout=30,
        )
        return normalize_layout(result.stdout)[:max_chars] if result.stdout else ""

    from pypdf import PdfReader

    # pypdf logs one "Skipping broken line ... Odd-length string" per glyph-list
    # entry it cannot parse in the font PyMuPDF embedded -- thousands of lines per
    # document, which buried the actual result in a 460 KB CI log the first time
    # this ran. It is noise about the font table, not about the text, and the
    # product does not suppress it; this is quietened for THIS tool's output only.
    logging.getLogger("pypdf").setLevel(logging.ERROR)

    chunks = []
    reader = PdfReader(str(path))
    for page in reader.pages:
        chunks.append(page.extract_text() or "")
        if sum(len(chunk) for chunk in chunks) > max_chars:
            break
    return normalize_layout("\n".join(chunks))[:max_chars]


def locate(label_text: str, extracted: str, expected_ratio: float) -> int | None:
    """Offset of `label_text` in `extracted`, or None when it is not there at all.

    Corpus offsets index the .txt source. Rendering to DOCX or PDF and extracting
    again moves everything, so each label has to be found afresh. Where the same
    string occurs more than once -- a party named in the heading and again in the
    signature block -- the occurrence nearest the label's relative position in the
    source is taken, which keeps a repeated name anchored to the right mention.

    Returning None is a result, not an error: it means the entity did not survive
    extraction intact. That is what a page-footer digit landing inside a name
    looks like from here, and it is reported as `unlocatable` rather than folded
    into recall, because no detector could have found what was not in the text.
    """
    occurrences = [match.start() for match in re.finditer(re.escape(label_text), extracted)]
    if not occurrences:
        return None
    if len(occurrences) == 1:
        return occurrences[0]
    target = expected_ratio * len(extracted)
    return min(occurrences, key=lambda offset: abs(offset - target))


# A layout artifact separates an entity's WORDS; it does not corrupt a word from
# the inside. So the search that decides "is this entity really absent" walks the
# entity's tokens and allows a bounded gap between them: whitespace, optionally
# one short intruding token such as a running page number, then whitespace again.
# The gap is bounded so that two unrelated occurrences of the first and last word
# cannot be stitched together into a false "it is there really".
_GAP = r"\s+(?:\S{1,12}\s+)?"


def diagnose_unlocatable(label_text: str, extracted: str) -> str:
    """Say WHY an entity is not in the extracted text, in one word.

    Three answers, and they mean different things to whoever reads the report:

    ``interleaved``
        The entity's words are all there in order, but something that is not
        whitespace sits between two of them -- a running page number is the case
        this exists to name. The entity is on screen and looks intact to a reader,
        and the document still produces findings, so nothing downstream notices;
        it simply cannot be matched, approved or redacted as one span.
    ``wrapped``
        The words are all there, separated only by extra whitespace, so the layout
        broke the entity across a line. Still unredactable -- redaction is an exact
        match against a document part whose text carries the break -- but a layout
        fact rather than a stray token.
    ``absent``
        Not there at all; the extractor dropped or mangled it.

    Sorting these apart matters because only ``absent`` is lost text, and lumping
    all three under one count would make a page footer look like data loss and
    data loss look like a page footer.
    """
    tokens = label_text.split()
    if len(tokens) < 2:
        return "absent"
    pattern = re.compile(_GAP.join(re.escape(token) for token in tokens))
    match = pattern.search(extracted)
    if match is None:
        return "absent"
    gaps = re.split("|".join(re.escape(token) for token in tokens), match.group(0))
    return "interleaved" if any(gap.strip() for gap in gaps) else "wrapped"


@dataclass
class DocumentResult:
    doc_id: str
    lang: str
    fmt: str
    extraction_status: str
    unlocatable: list[dict]
    misses: list[dict]
    partials: list[dict]
    false_positives: list[dict]
    unscored_findings: collections.Counter
    # The second dimension, on the rendering an "approve all" review exports.
    entities: int = 0
    entities_removed: int = 0
    operative_terms: int = 0
    operative_terms_kept: int = 0
    terms_by_kind: dict | None = None
    characters: int = 0
    passage_characters_removed: int = 0


def evaluate_document(doc: dict, source_text: str, path: Path, fmt: str):
    """Score one corpus document in one format. Returns (scores, DocumentResult)."""
    if fmt in PDF_FORMATS:
        extracted = extract_pdf_with(fmt.split("-", 1)[1], path)
        warning = None if extracted else "PDF text extraction returned no text; OCR may be required."
        language_text = None
    else:
        extracted, warning, language_text = extract_document(path)
    profile = analyze_privacy(path.name, extracted, warning, language_text=language_text)
    findings = profile["risk_map"]

    gold: list[Span] = []
    unlocatable: list[dict] = []
    for label in doc["labels"]:
        ratio = label["start"] / len(source_text) if source_text else 0.0
        offset = locate(label["text"], extracted, ratio)
        if offset is None:
            unlocatable.append(
                {
                    "category": label["category"],
                    "text": label["text"],
                    "cause": diagnose_unlocatable(label["text"], extracted),
                }
            )
            continue
        gold.append(Span(label["category"], offset, offset + len(label["text"])))

    finding_spans = [Span(f["category"], f["start"], f["end"]) for f in findings]
    scores = score_spans(gold, finding_spans)

    by_category: dict[str, list[tuple[int, int]]] = collections.defaultdict(list)
    for span in finding_spans:
        by_category[span.category].append((span.start, span.end))
    matched: set[tuple[str, int, int]] = set()
    misses: list[dict] = []
    partials: list[dict] = []
    for label in gold:
        hits = [s for s in by_category.get(label.category, []) if s[0] < label.end and s[1] > label.start]
        if not hits:
            misses.append({"category": label.category, "text": extracted[label.start:label.end]})
            continue
        for hit in hits:
            matched.add((label.category, hit[0], hit[1]))
        if not covers(hits, label.start, label.end):
            partials.append(
                {
                    "category": label.category,
                    "gold": extracted[label.start:label.end],
                    "covered": [extracted[a:b] for a, b in hits],
                }
            )

    # Both dimensions are read off the same rendering: every finding approved,
    # the worst case a reviewer's "approve all" produces. Privacy protection
    # counts the located entities whose every character is replaced; legal
    # semantic preservation counts the operative terms that still read.
    rendering = render(extracted, findings)
    semantic = legal_semantic_preservation(extracted, rendering.text)

    false_positives: list[dict] = []
    unscored: collections.Counter = collections.Counter()
    for finding in findings:
        if finding["category"] in UNSCORED_CATEGORIES:
            unscored[finding["category"]] += 1
            continue
        if (finding["category"], finding["start"], finding["end"]) not in matched:
            false_positives.append({"category": finding["category"], "sample": finding["sample"][:80]})

    result = DocumentResult(
        doc_id=doc["id"],
        lang=doc["lang"],
        fmt=fmt,
        extraction_status=profile["extraction_status"]["status"],
        unlocatable=unlocatable,
        misses=misses,
        partials=partials,
        false_positives=false_positives,
        unscored_findings=unscored,
        entities=len(gold),
        entities_removed=sum(1 for label in gold if entity_removed(rendering, label.start, label.end)),
        operative_terms=semantic.terms,
        operative_terms_kept=semantic.kept,
        terms_by_kind=semantic.by_kind,
        characters=len(extracted),
        passage_characters_removed=passage_characters_removed(rendering, CONTEXT_SWEEP_CATEGORIES),
    )
    return scores, result


