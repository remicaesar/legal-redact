def run_eval(labels_path: Path, formats: tuple[str, ...], workdir: Path) -> dict:
    spec = json.loads(labels_path.read_text(encoding="utf-8"))
    corpus_dir = labels_path.parent / "corpus"

    totals: dict[tuple[str, str, str], CategoryScore] = collections.defaultdict(CategoryScore)
    unlocatable: collections.Counter = collections.Counter()
    unlocatable_causes: collections.Counter = collections.Counter()
    unscored: collections.Counter = collections.Counter()
    dimensions: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    terms_by_kind: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    documents: list[DocumentResult] = []

    for doc in spec["documents"]:
        source_text = (corpus_dir / doc["path"]).read_text(encoding="utf-8")
        for fmt in formats:
            if fmt == "txt":
                path = corpus_dir / doc["path"]
            elif fmt == "docx":
                path = workdir / f"{doc['id']}.docx"
                render_docx(source_text, path)
            else:
                # One rendered PDF, read by both engines: the difference measured
                # is the extractor's, not the renderer's.
                path = workdir / f"{doc['id']}.pdf"
                if not path.exists():
                    render_pdf(source_text, path)

            scores, result = evaluate_document(doc, source_text, path, fmt)
            for category, score in scores.items():
                total = totals[(fmt, doc["lang"], category)]
                total.gold += score.gold
                total.detected += score.detected
                total.fully_covered += score.fully_covered
                total.findings += score.findings
                total.false_positives += score.false_positives
            for entry in result.unlocatable:
                unlocatable[(fmt, doc["lang"], entry["category"])] += 1
                unlocatable_causes[(fmt, doc["lang"], entry["cause"])] += 1
            for category, count in result.unscored_findings.items():
                unscored[(fmt, doc["lang"], category)] += count
            bucket = dimensions[f"{fmt}|{doc['lang']}"]
            bucket["entities"] += result.entities
            bucket["entities_removed"] += result.entities_removed
            bucket["operative_terms"] += result.operative_terms
            bucket["operative_terms_kept"] += result.operative_terms_kept
            bucket["characters"] += result.characters
            bucket["passage_characters_removed"] += result.passage_characters_removed
            for kind, counts in (result.terms_by_kind or {}).items():
                terms_by_kind[f"{fmt}|{doc['lang']}|{kind}"]["terms"] += counts["terms"]
                terms_by_kind[f"{fmt}|{doc['lang']}|{kind}"]["kept"] += counts["kept"]
            documents.append(result)

    return {
        "corpus": {
            "labels_path": str(labels_path.relative_to(PROJECT_DIR)),
            "seed": spec.get("seed"),
            "documents": len(spec["documents"]),
            "labelled_spans": sum(len(d["labels"]) for d in spec["documents"]),
            "formats": list(formats),
            "note": spec.get("note", ""),
        },
        "by_format_language_category": {
            f"{fmt}|{lang}|{category}": score.as_dict()
            for (fmt, lang, category), score in sorted(totals.items())
        },
        "headline": _headline(totals, unlocatable),
        "unlocatable": {f"{f}|{l}|{c}": n for (f, l, c), n in sorted(unlocatable.items())},
        "unlocatable_causes": {f"{f}|{l}|{c}": n for (f, l, c), n in sorted(unlocatable_causes.items())},
        "unscored_findings": {f"{f}|{l}|{c}": n for (f, l, c), n in sorted(unscored.items())},
        "two_dimensions": {key: _dimension_row(counts) for key, counts in sorted(dimensions.items())},
        "operative_terms_by_kind": {key: dict(counts) for key, counts in sorted(terms_by_kind.items())},
        "documents": [
            {
                "id": d.doc_id,
                "lang": d.lang,
                "format": d.fmt,
                "extraction_status": d.extraction_status,
                "unlocatable": d.unlocatable,
                "misses": d.misses,
                "partials": d.partials,
                "false_positives": d.false_positives,
            }
            for d in documents
        ],
        "reading": (
            "recall counts a gold entity as detected when a same-category finding OVERLAPS it. "
            "full_span_recall additionally requires those findings to cover the whole entity -- "
            "it is the figure that predicts the exported file. unlocatable counts entities that "
            "did not survive text extraction at all and are excluded from both, because they are "
            "an extraction defect rather than a detection one. These numbers are REPORTED, not "
            "gated: gold/ + accuracy_audit.py is the regression ratchet, this is the measurement."
        ),
    }


def _dimension_row(counts: collections.Counter) -> dict:
    row = dict(counts)
    row["privacy_protection"] = (
        round(counts["entities_removed"] / counts["entities"], 4) if counts["entities"] else None
    )
    row["legal_semantic_preservation"] = (
        round(counts["operative_terms_kept"] / counts["operative_terms"], 4) if counts["operative_terms"] else None
    )
    row["passage_share"] = (
        round(counts["passage_characters_removed"] / counts["characters"], 4) if counts["characters"] else None
    )
    return row


def _headline(totals, unlocatable) -> dict:
    headline: dict[str, dict] = {}
    for (fmt, lang, _category), score in totals.items():
        bucket = headline.setdefault(
            f"{fmt}|{lang}",
            {"gold": 0, "detected": 0, "fully_covered": 0, "findings": 0, "false_positives": 0, "unlocatable": 0},
        )
        bucket["gold"] += score.gold
        bucket["detected"] += score.detected
        bucket["fully_covered"] += score.fully_covered
        bucket["findings"] += score.findings
        bucket["false_positives"] += score.false_positives
    for (fmt, lang, _category), count in unlocatable.items():
        headline.setdefault(
            f"{fmt}|{lang}",
            {"gold": 0, "detected": 0, "fully_covered": 0, "findings": 0, "false_positives": 0, "unlocatable": 0},
        )["unlocatable"] += count
    for bucket in headline.values():
        gold, findings = bucket["gold"], bucket["findings"]
        bucket["recall"] = round(bucket["detected"] / gold, 4) if gold else None
        bucket["full_span_recall"] = round(bucket["fully_covered"] / gold, 4) if gold else None
        bucket["precision"] = (
            round((findings - bucket["false_positives"]) / findings, 4) if findings else None
        )
    return dict(sorted(headline.items()))


