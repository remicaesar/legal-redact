_DOCX_CONTENT_TYPES = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>
"""

_DOCX_RELS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>
"""


def _xml_escape(value: str) -> str:
    return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render_docx(text: str, path: Path) -> None:
    """Write `text` as a minimal DOCX, one paragraph per source line.

    Hand-built rather than via python-docx, which is not a dependency of this
    repo.

    `xml:space="preserve"` is here for fidelity to the format, not for this
    measurement: the corpus aligns labels in columns ("ADRES      : ..."), Word
    collapses those runs without the attribute, and a DOCX this tool writes
    should be one Word would read back unchanged. It makes no difference to what
    `extraction.extract_docx_text` returns -- measured, identical with and
    without -- because ElementTree does not implement XML whitespace-stripping
    semantics. Dropping it is therefore an equivalent mutant here; do not read
    the attribute as load-bearing for the numbers.
    """
    from zipfile import ZIP_DEFLATED, ZipFile

    paragraphs = "".join(
        f'<w:p><w:r><w:t xml:space="preserve">{_xml_escape(line)}</w:t></w:r></w:p>'
        for line in text.split("\n")
    )
    document = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        f"<w:body>{paragraphs}</w:body></w:document>"
    )
    with ZipFile(path, "w", ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", _DOCX_CONTENT_TYPES)
        archive.writestr("_rels/.rels", _DOCX_RELS)
        archive.writestr("word/document.xml", document)


# Enough lines that a corpus document runs to several pages, so its running
# footer lands inside the body text rather than politely after it -- a page
# number between two words of a name is genuinely in the extracted stream, and
# no parser is at fault. The wrap is wide enough to hold an ordinary address on
# one line: a narrower page splits nearly every English address and the
# resulting unlocatable count would be a fact about this renderer rather than
# about PDFs.
PDF_LINES_PER_PAGE = 26
PDF_WRAP_COLUMNS = 104


def _wrap(text: str, columns: int = PDF_WRAP_COLUMNS) -> list[str]:
    lines: list[str] = []
    for source_line in text.split("\n"):
        if len(source_line) <= columns:
            lines.append(source_line)
            continue
        current = ""
        for word in source_line.split(" "):
            candidate = f"{current} {word}".strip()
            if len(candidate) > columns and current:
                lines.append(current)
                current = word
            else:
                current = candidate
        lines.append(current)
    return lines


def render_pdf(text: str, path: Path) -> None:
    """Write `text` as a multi-page PDF with a page-number footer on every page.

    Text is written with PyMuPDF's TextWriter rather than page.insert_text: the
    latter encodes as Latin-1, so every Turkish dotted/dotless i, ş, ğ and ç in
    the corpus comes back as a replacement character and the whole PDF arm would
    be measuring a broken renderer. TextWriter maps glyphs properly and the
    built-in Helvetica carries the Turkish set, so this needs no font file and
    behaves the same on a CI runner as it does on a laptop.
    """
    import pymupdf

    font = pymupdf.Font("helv")
    lines = _wrap(text)
    document = pymupdf.open()
    for page_index in range(0, max(len(lines), 1), PDF_LINES_PER_PAGE):
        page = document.new_page(width=660, height=740)
        writer = pymupdf.TextWriter(page.rect)
        for row, line in enumerate(lines[page_index:page_index + PDF_LINES_PER_PAGE]):
            if line:
                writer.append((48, 54 + row * 24), line, font=font, fontsize=10)
        writer.append((48, 706), str(page_index // PDF_LINES_PER_PAGE + 1), font=font, fontsize=9)
        writer.write_text(page)
    document.save(path)
    document.close()


