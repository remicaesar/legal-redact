# Rules that match a sensitive CLAUSE or a party role rather than an identifier.
# The corpus deliberately does not label them -- a clause has no single right
# boundary to label -- so scoring them for precision would report every one of
# them as a false positive by construction, which is a statement about the corpus
# and not about the rule. Their volume is reported separately, as review burden,
# because that is the honest thing it measures.
UNSCORED_CATEGORIES = frozenset(
    {"party_role", "health_data", "criminal_allegation", "privileged_or_confidential"}
)


