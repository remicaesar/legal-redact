def format_tables(report: dict) -> str:
    lines: list[str] = []
    headline = report["headline"]
    lines.append("HEADLINE")
    lines.append(
        f"{'format/lang':14s} {'gold':>5s} {'recall':>7s} {'fullspan':>9s} "
        f"{'precision':>10s} {'findings':>9s} {'unlocatable':>12s}"
    )
    for key, bucket in headline.items():
        lines.append(
            f"{key:14s} {bucket['gold']:5d} "
            f"{_fmt(bucket['recall']):>7s} {_fmt(bucket['full_span_recall']):>9s} "
            f"{_fmt(bucket['precision']):>10s} {bucket['findings']:9d} {bucket['unlocatable']:12d}"
        )

    lines.append("")
    lines.append("TWO DIMENSIONS (every finding approved)")
    lines.append(f"{'format/lang':14s} {'privacy':>8s} {'semantic':>9s} {'passages':>9s}")
    for key, row in report["two_dimensions"].items():
        lines.append(
            f"{key:14s} {_fmt(row['privacy_protection']):>8s} "
            f"{_fmt(row['legal_semantic_preservation']):>9s} {_fmt(row['passage_share']):>9s}"
        )

    for fmt in report["corpus"]["formats"]:
        for lang in ("tr", "en"):
            rows = {
                key.split("|")[2]: value
                for key, value in report["by_format_language_category"].items()
                if key.startswith(f"{fmt}|{lang}|")
            }
            if not rows:
                continue
            lines.append("")
            lines.append(f"{fmt.upper()} / {lang.upper()}")
            lines.append(
                f"  {'category':30s} {'gold':>5s} {'det':>5s} {'recall':>7s} "
                f"{'full':>5s} {'fullrec':>8s} {'findings':>9s} {'FP':>4s} {'prec':>7s}"
            )
            for category, row in sorted(rows.items()):
                lines.append(
                    f"  {category:30s} {row['gold']:5d} {row['detected']:5d} "
                    f"{_fmt(row['recall']):>7s} {row['fully_covered']:5d} "
                    f"{_fmt(row['full_span_recall']):>8s} {row['findings']:9d} "
                    f"{row['false_positives']:4d} {_fmt(row['precision']):>7s}"
                )
    return "\n".join(lines)


def _fmt(value: float | None) -> str:
    return "-" if value is None else f"{value:.3f}"


def render_docs(report: dict) -> str:
    """The committed accuracy page, generated so a README claim can cite a real run.

    Written by CI and compared against the committed copy, so a detection change
    that moves a number cannot merge without the number moving with it. This is
    the discipline the prose numbers did not have: README.md, gold/README.md and
    a fresh audit run reported three different precision figures at the time this
    was written, none of them current.
    """
    corpus = report["corpus"]
    out = [
        "<!-- GENERATED by accuracy_eval.py --write-docs. Do not edit by hand. -->",
        "# Measured detection accuracy",
        "",
        "These figures come from the **held-out** evaluation corpus in `eval/`, regenerated and",
        "re-measured by CI on every push. They are not the `gold/` regression-ratchet numbers:",
        "`gold/` is fitted (its labels and the detection rules were edited in the same commits,",
        "so its recall is 1.000 by construction), and `eval/` is not used to tune anything,",
        "except as recorded in the caveat below.",
        "",
        "**Caveat: English person names are no longer a clean held-out figure.** The rule shapes",
        "behind the English signature-line and e-mail name paths (added 2026-11-24) were derived",
        "from reading which `eval/` English person names were missed, on 2026-11-24 (see \"Names a",
        "document spells for you\" in `gold/README.md`). The English `natural_person_name` figures",
        "below are therefore partly fitted; the last clean held-out English person-name recall",
        "was **0.882**, measured before that change.",
        "",
        f"Corpus: **{corpus['documents']} synthetic documents**, "
        f"**{corpus['labelled_spans']} labelled entity spans**, Turkish and English, "
        f"rendered as {', '.join('`.' + f + '`' for f in corpus['formats'])} "
        f"(generator seed `{corpus['seed']}`).",
        "All personal data in it is invented; see `eval/README.md`.",
        "",
        "Reproduce with:",
        "",
        "```bash",
        "python3 eval/generate_corpus.py --check   # the corpus is what the generator says",
        "python3 accuracy_eval.py                  # the numbers below",
        "```",
        "",
        "## Headline",
        "",
        "| corpus | entities | recall | full-span recall | precision | findings | unlocatable |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for key, bucket in report["headline"].items():
        fmt, lang = key.split("|")
        out.append(
            f"| `.{fmt}` / {lang.upper()} | {bucket['gold']} | {_fmt(bucket['recall'])} | "
            f"{_fmt(bucket['full_span_recall'])} | {_fmt(bucket['precision'])} | "
            f"{bucket['findings']} | {bucket['unlocatable']} |"
        )
    out += [
        "",
        "**recall** — a same-category finding overlaps the entity anywhere.",
        "**full-span recall** — those findings cover the *whole* entity. Redaction removes what a",
        "finding covers, so this is the column that predicts the exported file; the gap between the",
        "two is text that ships.",
        "**precision** — over labelled categories only. Clause and party-role rules are not labelled",
        "by the corpus and are reported separately below as review burden, not as false positives.",
        "**unlocatable** — entities that did not survive text extraction, so no detector could have",
        "found them. Counted apart from recall on purpose: it is an extraction defect.",
        "",
        "## Per category",
        "",
    ]
    for fmt in corpus["formats"]:
        for lang in ("tr", "en"):
            rows = {
                key.split("|")[2]: value
                for key, value in report["by_format_language_category"].items()
                if key.startswith(f"{fmt}|{lang}|")
            }
            if not rows:
                continue
            out += [
                f"### `.{fmt}` / {lang.upper()}",
                "",
                "| category | entities | detected | recall | full-span recall | findings | FP | precision |",
                "|---|---:|---:|---:|---:|---:|---:|---:|",
            ]
            for category, row in sorted(rows.items()):
                out.append(
                    f"| `{category}` | {row['gold']} | {row['detected']} | {_fmt(row['recall'])} | "
                    f"{_fmt(row['full_span_recall'])} | {row['findings']} | "
                    f"{row['false_positives']} | {_fmt(row['precision'])} |"
                )
            out.append("")

    if report["unscored_findings"]:
        out += [
            "## Unscored findings (review burden)",
            "",
            "Clause and party-role rules the corpus does not label. Reported because the count is a",
            "real cost to the reviewer, not because it is an error.",
            "",
            "| corpus | category | findings |",
            "|---|---|---:|",
        ]
        for key, count in report["unscored_findings"].items():
            fmt, lang, category = key.split("|")
            out.append(f"| `.{fmt}` / {lang.upper()} | `{category}` | {count} |")
        out.append("")

    out += [
        "## Two dimensions: privacy protection and legal semantic preservation",
        "",
        "Recall says whether an identifier was *found*. It cannot see a pass that removes every",
        "identifier by deleting the clauses around them -- which scores perfectly and leaves a",
        "document no reviewer can analyse. So the exported text is scored twice, with **every",
        "finding approved** (the worst case, and what a reviewer's \"approve all\" produces):",
        "",
        "| corpus | entities removed | privacy protection | operative terms kept | legal semantic preservation | passage characters removed |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for key, row in report["two_dimensions"].items():
        fmt, lang = key.split("|")
        out.append(
            f"| `.{fmt}` / {lang.upper()} | {row['entities_removed']} / {row['entities']} | "
            f"{_fmt(row['privacy_protection'])} | {row['operative_terms_kept']} / {row['operative_terms']} | "
            f"{_fmt(row['legal_semantic_preservation'])} | {_fmt(row['passage_share'])} |"
        )
    out += [
        "",
        "**privacy protection** — located entities whose every character is replaced in the export.",
        "It differs from full-span recall in two ways, both because it reads the deliverable: a",
        "replacement counts whatever its finding's category, and the export replaces every",
        "occurrence of an approved sample, not only the one the finding was raised on.",
        "**legal semantic preservation** — occurrences of legally operative terms",
        "(`legal_analyzer/legal_semantics.py`: penalty, confidentiality definition and exceptions,",
        "obligations, rights, durations, survival, governing law, jurisdiction, parties' roles, …)",
        "that still read in the export, counted per term so one deleted clause out of three shows.",
        "It is lexical: it says the operative words are there, not that a reader draws the right",
        "conclusion from them. The term dictionary was written from legal vocabulary and the",
        "synthetic NDA in `tests/fixtures/nda/`, not from this corpus.",
        "**passage characters removed** — the share of the document replaced as whole passages by",
        "the clause-level rules (health data, criminal allegation, privilege), as opposed to values.",
        "",
        "## The two PDF rows are not a formatting choice",
        "",
        "`legal_analyzer/extraction.extract_pdf_text` uses `pdftotext -layout` when poppler is on",
        "PATH and falls back to pypdf when it is not. Both rows above are the same rendered PDFs,",
        "read by the two branches, and they do not agree — so **a PDF's accuracy here depends on",
        "what is installed on the machine that scans it**, with nothing on screen saying which one",
        "ran. The Docker image and a laptop with Homebrew poppler are not the same scanner.",
        "",
        "## What these numbers do not say",
        "",
        "- The corpus is **synthetic**. It measures the rules against the document shapes the",
        "  generator knows how to write, which is a ceiling: Turkish matter numbers score well here",
        "  partly because the generator writes them in the labelled `Esas No: 2025/417` form, while",
        "  the `2025/417 E.` citation form real decisions use is not matched at all.",
        "- It is **not a production accuracy claim**. Extend it with hand-labelled real documents",
        "  before treating any figure here as what a lawyer would see on their own files.",
        "- A figure moving is information, not a failure. Nothing here is gated at a floor; gating it",
        "  would turn the measurement into a second ratchet and lose exactly what it was built for.",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--labels", type=Path, default=DEFAULT_LABELS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--formats",
        default=",".join(ALL_FORMATS),
        help=f"comma-separated subset of {','.join(ALL_FORMATS)} (default: all)",
    )
    parser.add_argument("--write-docs", action="store_true", help=f"rewrite {DOCS_PATH.name}")
    parser.add_argument(
        "--check-docs",
        action="store_true",
        help="exit non-zero when the committed accuracy page does not match this run",
    )
    args = parser.parse_args()

    if not args.labels.exists():
        raise SystemExit(f"Eval corpus not found: {args.labels} (run python3 eval/generate_corpus.py)")

    formats = tuple(f.strip() for f in args.formats.split(",") if f.strip())
    unknown = [f for f in formats if f not in ALL_FORMATS]
    if unknown:
        raise SystemExit(f"Unknown format(s): {', '.join(unknown)}")

    with tempfile.TemporaryDirectory() as tmp:
        report = run_eval(args.labels, formats, Path(tmp))

    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(format_tables(report))
    print(f"\nEval report written: {args.output}")

    page = render_docs(report)
    if args.write_docs:
        DOCS_PATH.parent.mkdir(parents=True, exist_ok=True)
        DOCS_PATH.write_text(page, encoding="utf-8")
        print(f"Accuracy page written: {DOCS_PATH}")
    if args.check_docs:
        if set(formats) != set(ALL_FORMATS):
            raise SystemExit("--check-docs compares a full run; do not combine it with --formats")
        current = DOCS_PATH.read_text(encoding="utf-8") if DOCS_PATH.exists() else ""
        if current != page:
            print(
                f"\n{DOCS_PATH} is stale. Regenerate with:\n"
                "  python3 accuracy_eval.py --write-docs",
                file=sys.stderr,
            )
            raise SystemExit(1)
        print(f"{DOCS_PATH} matches this run.")


if __name__ == "__main__":
    main()
