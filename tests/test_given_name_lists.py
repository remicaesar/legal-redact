"""The given-name lists built from official statistics, and what they must not do.

`legal_analyzer/given_names_en.py` and `given_names_tr.py` are generated by
`build_given_names.py` from US Social Security Administration, ONS and TÜİK
name statistics, with a homograph filter in front of them. A bigger list finds
more people and also more words that only look like given names; two of those
were measured before the filter existed -- "Kira Bedeli" (Turkish for "rent
amount", and "Kira" is a US given name) read as a person in a lease, and
"London EC" read as one in an English address. These tests hold the filter's
result without needing the source files, which are not in the repository.

Every person, address and document here is invented.
"""

from __future__ import annotations

import re
import unittest
from pathlib import Path

import build_given_names
from legal_analyzer import english_names, given_names_en, given_names_tr, turkish_names, turkish_places
from legal_analyzer.privacy import analyze_privacy

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "names"


def person_spans(text: str) -> list[tuple[int, int]]:
    return [
        (f["start"], f["end"])
        for f in analyze_privacy("document.txt", text)["risk_map"]
        if f["category"] == "natural_person_name"
    ]


def overlaps_a_person(text: str, needle: str) -> bool:
    start = text.index(needle)
    end = start + len(needle)
    return any(s < end and start < e for s, e in person_spans(text))


class HomographsAreNotPeopleTests(unittest.TestCase):
    def test_the_measured_false_positives_stay_gone(self):
        lease = (FIXTURES / "tr_listed_given_names.txt").read_text(encoding="utf-8")
        for needle in ("Kira Bedeli", "Kira Artışı", "Kuzey Cephesi", "Hava Durumu", "Savaş Hali", "Duran Varlıklar", "Dönen Varlıklar"):
            with self.subTest(needle=needle):
                self.assertFalse(overlaps_a_person(lease, needle))
        note = (FIXTURES / "en_listed_given_names.txt").read_text(encoding="utf-8")
        for needle in ("London EC2R", "Will and testament", "Mercedes Benz", "Montana Ridge", "Geneva Convention"):
            with self.subTest(needle=needle):
                self.assertFalse(overlaps_a_person(note, needle))

    def test_neither_gazetteer_carries_them(self):
        for word in ("Kira", "London", "Will", "Paris", "Kuzey", "Hava", "Savaş", "Rüzgar", "Duran", "Durmuş", "Yüksel", "Mercedes", "Geneva", "Montana"):
            with self.subTest(word=word):
                self.assertNotIn(english_names._fold(word), english_names.GIVEN_NAMES)
                self.assertNotIn(turkish_names.tr_fold(word), turkish_names.GIVEN_NAMES)

    def test_a_hand_written_name_that_is_also_a_word_is_kept_and_still_misreads(self):
        """The residual: Barış (peace) was on the hand-written list before the
        official one, and the filter only ever subtracts from what a source adds."""
        self.assertIn(turkish_names.tr_fold("Barış"), turkish_names._HAND_WRITTEN_GIVEN_NAMES)
        lease = (FIXTURES / "tr_listed_given_names.txt").read_text(encoding="utf-8")
        self.assertTrue(overlaps_a_person(lease, "Barış Görüşmesi"))

    def test_the_hand_curated_exclusions_survive_the_official_list(self):
        """Morgan, Taylor, Victoria ... are on the Social Security list; the
        English module leaves them out on purpose and the bigger list must not
        bring them back."""
        for word in english_names.EXCLUDED_HOMOGRAPHS:
            with self.subTest(word=word):
                self.assertNotIn(english_names._fold(word), english_names.GIVEN_NAMES)

    def test_no_listed_name_is_a_legal_or_structural_term(self):
        terms = build_given_names.legal_terms()
        for module in (given_names_en, given_names_tr):
            for name in module.NAMES:
                with self.subTest(module=module.__name__, name=name):
                    self.assertFalse(build_given_names.is_legal_term(name, terms))

    def test_no_listed_name_is_a_province(self):
        for module in (given_names_en, given_names_tr):
            for name in module.NAMES:
                with self.subTest(module=module.__name__, name=name):
                    self.assertFalse(turkish_places.is_province(turkish_names.tr_fold(name)))

    def test_every_listed_name_is_one_plain_word(self):
        plain = re.compile(r"[^\W\d_](?:[^\W\d_]|['’\-])*[^\W\d_]")
        for module in (given_names_en, given_names_tr):
            for name in module.NAMES:
                with self.subTest(module=module.__name__, name=name):
                    self.assertTrue(plain.fullmatch(name) and len(name) >= 3)


class TheListsFindPeopleTests(unittest.TestCase):
    def test_a_name_only_the_official_lists_know_is_found_in_plain_prose(self):
        cases = {
            "The meeting was attended by Cornelius Wetherby yesterday.": "Cornelius Wetherby",
            "Toplantıya Necdet Kocabıyık da katılmıştır.": "Necdet Kocabıyık",
        }
        for text, name in cases.items():
            with self.subTest(name=name):
                start = text.index(name)
                self.assertIn((start, start + len(name)), person_spans(text))

    def test_the_hand_written_lists_are_kept_whole(self):
        self.assertLessEqual(
            english_names._HAND_WRITTEN_GIVEN_NAMES
            - {english_names._fold(name) for name in turkish_names.GIVEN_NAMES},
            english_names.GIVEN_NAMES,
        )
        self.assertLessEqual(turkish_names._HAND_WRITTEN_GIVEN_NAMES, turkish_names.GIVEN_NAMES)


class BuildStepTests(unittest.TestCase):
    """The build's own selection and rendering, on invented inputs: the source
    files are not in the repository, so `build_given_names.py --check` is run by
    hand against them, not here."""

    def test_each_filter_removes_its_names_and_reports_how_many(self):
        kept, counts = build_given_names.select(
            {"Zorbek", "Quillan", "Ab", "Bad1", "Kuzey", "Mercedes"},
            [
                ("a dictionary word", lambda name: name == "Kuzey"),
                ("a brand", lambda name: name == "Mercedes"),
            ],
        )
        self.assertEqual(kept, ["Quillan", "Zorbek"])
        self.assertEqual(
            counts,
            [("shorter than three letters or not a plain word", 2), ("a dictionary word", 1), ("a brand", 1)],
        )

    def test_a_circumflex_spelling_matches_the_plain_one(self):
        self.assertTrue(build_given_names._folds("Rüzgar") & build_given_names._folds("rüzgâr"))

    def test_a_rendered_module_carries_exactly_the_names_it_was_given(self):
        names = ["Quillan", "Zorbek", "Ömercan"]
        namespace: dict = {}
        exec(build_given_names.render("Invented.", names), namespace)
        self.assertEqual(namespace["NAMES"], frozenset(names))


if __name__ == "__main__":
    unittest.main()
